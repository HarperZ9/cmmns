// Builds src/core/confusables-data.js from the Unicode confusables table (UTS #39,
// confusables.txt). CMMNS keeps only single letters that look like a single letter of another
// script among Latin, Cyrillic, Greek, Armenian and Cherokee, matched by case, for folding
// look-alike letters inside mixed-script words before matching (src/core/confusables.js).
//   node scripts/confusables-build.mjs <path to confusables.txt>
// The file is read from disk, never fetched at run time. Download it from
// https://www.unicode.org/Public/security/latest/confusables.txt (Unicode License v3).
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { join, dirname } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const SCRIPTS = ["Latin", "Cyrillic", "Greek", "Armenian", "Cherokee"];
const RX = Object.fromEntries(SCRIPTS.map((s) => [s, new RegExp(`^\\p{Script=${s}}$`, "u")]));
export const scriptOf = (c) => (/^\p{L}$/u.test(c) ? SCRIPTS.find((s) => RX[s].test(c)) || null : null);
const caseOf = (c) => (c !== c.toLowerCase() ? "upper" : c !== c.toUpperCase() ? "lower" : "none");

// Parses confusables.txt into classes: prototype -> [letters in the five scripts].
export function classes(txt) {
  const proto = new Map();
  for (const line of txt.split(/\r?\n/)) {
    const m = line.match(/^([0-9A-F]+)\s*;\s*([0-9A-F ]+?)\s*;\s*MA/);
    if (!m) continue;
    const src = String.fromCodePoint(parseInt(m[1], 16));
    const tgt = m[2].trim().split(/\s+/).map((h) => String.fromCodePoint(parseInt(h, 16))).join("");
    if ([...tgt].length !== 1) continue;
    proto.set(src, tgt);
  }
  const out = new Map();
  const add = (p, c) => { if (!scriptOf(c)) return; if (!out.has(p)) out.set(p, new Set()); out.get(p).add(c); };
  for (const [src, tgt] of proto) { add(tgt, src); add(tgt, tgt); }
  return out;
}

// For each script, a map from a letter of another script to the look-alike letter of this script
// with the same case. Basic alphabets win ties (Cyrillic а-я, Greek α-ω, Latin a-z).
const BASIC = { Latin: /^[A-Za-z]$/, Cyrillic: /^[\u0410-\u044F\u0401\u0451]$/, Greek: /^[\u0391-\u03A9\u03B1-\u03C9]$/ };
export function tables(cls) {
  const T = { Latin: new Map(), Cyrillic: new Map(), Greek: new Map() };
  for (const members of cls.values()) {
    const list = [...members].sort();
    for (const target of Object.keys(T)) {
      for (const c of list) {
        if (scriptOf(c) === target) continue;
        const pick = list.filter((x) => scriptOf(x) === target && caseOf(x) === caseOf(c)).sort((a, b) => (BASIC[target].test(b) ? 1 : 0) - (BASIC[target].test(a) ? 1 : 0))[0];
        if (pick && !T[target].has(c)) T[target].set(c, pick);
      }
    }
  }
  return T;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const file = process.argv[2];
  if (!file) { console.error("usage: node scripts/confusables-build.mjs <confusables.txt>"); process.exit(1); }
  const txt = readFileSync(file, "utf8");
  const version = (txt.match(/^# Version: (\S+)/m) || [])[1], date = (txt.match(/^# Date: ([^,]+)/m) || [])[1];
  const sha = createHash("sha256").update(readFileSync(file)).digest("hex");
  const T = tables(classes(txt));
  const flat = (m) => JSON.stringify([...m].sort().map(([a, b]) => a + b).join(""));
  const body = `// Generated by scripts/confusables-build.mjs from the Unicode confusables table. Do not edit.
// Source: confusables.txt, Unicode Security Mechanisms (UTS #39) version ${version}, dated ${date},
// SHA-256 ${sha}.
// Copyright © 1991-2026 Unicode, Inc. Distributed under the Unicode License v3
// (https://www.unicode.org/license.txt); data/confusables.README.md carries the notice in full.
// Each string is pairs of letters: a letter of another script, then its look-alike in this one.
export const CONFUSABLES_VERSION = ${JSON.stringify(version)};
export const TO_LATIN = ${flat(T.Latin)};
export const TO_CYRILLIC = ${flat(T.Cyrillic)};
export const TO_GREEK = ${flat(T.Greek)};
`;
  writeFileSync(join(root, "src/core/confusables-data.js"), body);
  console.log(`confusables-data.js: ${T.Latin.size} to Latin, ${T.Cyrillic.size} to Cyrillic, ${T.Greek.size} to Greek (UTS #39 ${version})`);
}
