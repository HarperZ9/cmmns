// Writes src/core/discourse/labels-data.js from the epithet lexicon, data/discourse/labels.json. Only the
// words go into the module: the aim (which side an entry is usually aimed at), the mirror, the source
// and the reason stay in the data file, where tests/discourse.labels.symmetry.test.js checks their
// balance. The label marker therefore cannot read a side.
//   node scripts/labels-data.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
export const LEXICON_PATH = join(ROOT, "data/discourse/labels.json");
export const MODULE_PATH = join(ROOT, "src/core/discourse/labels-data.js");

const pluralOf = (w) => (/[^aeiou]y$/.test(w) ? w.slice(0, -1) + "ies" : /(?:s|sh|ch|x|z)$/.test(w) ? w + "es" : w + "s");
const forms = (list) => list.map((e) => [e.word, e.plural || pluralOf(e.word)]);

// The module text for a lexicon object.
export function moduleText(lex) {
  const line = (name, v) => `export const ${name} = Object.freeze(${JSON.stringify(v)});\n`;
  return "// Generated by scripts/labels-data.mjs from data/discourse/labels.json. Do not edit. The words of the\n" +
    "// label marker's epithet lexicon, with no side or source: the data file holds those.\n" +
    line("LABEL_HEADS", forms(lex.heads)) + line("LABEL_MODIFIERS", lex.modifiers.map((e) => e.word)) +
    line("LABEL_INTENSIFIERS", lex.intensifiers) + line("LABEL_INSTITUTIONS", lex.institutions);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(MODULE_PATH, moduleText(JSON.parse(readFileSync(LEXICON_PATH, "utf8"))));
  console.log(`${MODULE_PATH} written`);
}
