// Tables of the signal detection measures (scripts/eval/sdt.mjs), one per sign: precision, hit rate,
// false-alarm rate, d' and c with their intervals, per corpus. The Markdown goes between markers in
// project-docs/EVALUATION.md; the HTML goes on the transparency page. Both read the "sdt" block of
// eval-results.json, so the two pages and the results file cannot drift apart.

export const NAMES = {
  dehumanise: "Dehumanising language", violence: "Call for violence", vigilante: "Call for vigilantes",
  slur: "Slur or coded hate term", slurSoft: "Context-dependent slur", stereotype: "Group stereotype",
  motive: "Motive attribution", essentialise: "Essentialising", conspiracy: "Conspiracy framing",
  absolutist: "Absolutist wording", contempt: "Contempt", strong: "Any strong language sign",
};
const CORPUS = { mhs: "Measuring Hate Speech", hatexplain: "HateXplain", civil: "Civil Comments", "mlma-fr": "MLMA (French)" };
// The sign's own label in each corpus that has one; Civil Comments labels threats, not violence as such.
const OWN = { dehumanise: "its own label (dehumanising)", violence: "its own label (violence)", stereotype: "its own label (stereotype)",
  "civil:violence": "its own label (threat)" };

export const HEAD = ["Corpus", "Scored against", "Precision", "Hit rate", "False-alarm rate", "d' (95% interval)", "c (95% interval)"];
const BEGIN = "<!-- sdt:begin (generated by scripts/eval-sdt.mjs; do not edit) -->";
const END = "<!-- sdt:end -->";

const n = (x) => x.toLocaleString("en");
const small = (x) => `${x === 0 ? 0 : Number((x * 100).toPrecision(2))}%`;
const share = (k, of) => (of ? `${small(k / of)} (${n(k)} of ${n(of)})` : "n/a");
const sgn = (x) => (x < 0 ? `−${Math.abs(x).toFixed(2)}` : x.toFixed(2));
const withCi = (v, ci) => `${sgn(v)} (${sgn(ci[0])} to ${sgn(ci[1])})`;

// The cells of one row, as plain text.
export function cells(r, family) {
  const fired = r.tp + r.fp, notYet = `not measured (fired ${n(fired)} ${fired === 1 ? "time" : "times"})`;
  return [
    r.corpora ? "Three English corpora, pooled" : CORPUS[r.corpus] || r.corpus,
    r.against === "specific" ? OWN[`${r.corpus}:${family}`] || OWN[family] || "its own label" : "general hostility",
    fired ? share(r.tp, fired) : "never fired",
    share(r.tp, r.tp + r.fn),
    share(r.fp, r.fp + r.tn),
    r.measured ? withCi(r.dprime, r.dCI) : notYet,
    r.measured ? withCi(r.c, r.cCI) : notYet,
  ];
}

// [family, rows] in a stable order: every family in NAMES with at least one row.
export function grouped(sdt) {
  return Object.keys(NAMES).map((f) => {
    const rows = sdt.rows.filter((r) => r.family === f);
    if (sdt.pooled && sdt.pooled[f]) rows.push({ ...sdt.pooled[f], family: f, against: "hostile" });
    return [f, rows];
  }).filter(([, rows]) => rows.length);
}

export function markdownTables(sdt) {
  const line = (c) => `| ${c.join(" | ")} |`;
  return grouped(sdt).map(([f, rows]) => [`#### ${NAMES[f]}`, "", line(HEAD), line(HEAD.map(() => "---")),
    ...rows.map((r) => line(cells(r, f))), ""].join("\n")).join("\n").trimEnd();
}

// Replace the generated block of EVALUATION.md; the text around it stays as written.
export function spliceSdt(md, sdt) {
  const a = md.indexOf(BEGIN), b = md.indexOf(END);
  if (a < 0 || b < a) throw new Error("EVALUATION.md has no sdt:begin / sdt:end markers");
  return md.slice(0, a + BEGIN.length) + "\n\n" + markdownTables(sdt) + "\n\n" + md.slice(b);
}

export function htmlTables(sdt, esc) {
  return grouped(sdt).map(([f, rows]) => `<h4>${esc(NAMES[f])}</h4>
<div class="scroll"><table><thead><tr>${HEAD.map((h) => `<th scope="col">${esc(h)}</th>`).join("")}</tr></thead><tbody>
${rows.map((r) => `<tr>${cells(r, f).map((c, i) => (i < 2 ? `<td>${esc(c)}</td>` : `<td class="num">${esc(c)}</td>`)).join("")}</tr>`).join("\n")}
</tbody></table></div>`).join("\n");
}
