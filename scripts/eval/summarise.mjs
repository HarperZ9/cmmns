// Turns the per-corpus results into the per-family figures the extension shows, and writes
// src/core/measured.js. Headline precision pools the English corpora with group-hostility labels;
// the range across corpora sits beside it so a reader sees the spread, not one flattering number.

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { rate, FAMILIES } from "./metrics.mjs";
import { currentBlock } from "./summarise-persuasion.mjs";

const ENGLISH = ["mhs", "hatexplain", "civil"];
const MIN_N = 20;

const pool = (results, f) => {
  let k = 0, n = 0;
  for (const c of ENGLISH) { const p = results[c].families[f].againstHostile.precision; k += p.k; n += p.n; }
  return rate(k, n);
};

export const DOES_NOT_PROVE = "Measured on public research corpora (Reddit, Twitter, Gab, YouTube and news comments), " +
  "not on this site's replies. Precision says how often a marker sat on text the annotators judged hostile to a group; " +
  "it does not say why anyone wrote it, and it can differ on other sites and topics.";

export function familySummary(results) {
  const out = {};
  for (const f of [...FAMILIES, "strong"]) {
    const byCorpus = Object.fromEntries(ENGLISH.map((c) => [c, results[c].families[f].againstHostile.precision]));
    const big = Object.values(byCorpus).filter((p) => p.n >= MIN_N).map((p) => p.value);
    const spec = results.mhs.families[f] && results.mhs.families[f].againstSpecific;
    const precision = pool(results, f);
    out[f] = {
      precision,
      precisionRange: big.length ? [Math.min(...big), Math.max(...big)] : null,
      byCorpus,
      specific: spec ? { against: `mhs:${f}`, precision: spec.precision, recall: spec.recall } : null,
      recall: spec ? spec.recall : null,
      measured: precision.n >= MIN_N,
      note: precision.n >= MIN_N ? null : `fewer than ${MIN_N} hits in the test split; not measured`,
    };
  }
  return out;
}

// Families the window shows that this evaluation measures (ids from src/core/families.js). Weak
// families never label a post, and the duplicate and mismatch pilots are synthetic, so neither
// gets a row: their badges keep saying "not measured yet".
export const SHOWN = ["dehumanise", "violence", "vigilante", "slur", "stereotype"];
const SOURCE = "Measuring Hate Speech, HateXplain and Civil Comments, pooled; see project-docs/EVALUATION.md";

export function tableRows(summary) {
  const rows = {};
  for (const f of SHOWN) {
    const x = summary.families[f];
    if (!x || !x.measured) continue;
    rows[f] = { precision: x.precision.value, low: x.precision.ci[0], high: x.precision.ci[1], n: x.precision.n, split: "test",
      recall: x.recall ? x.recall.value : null, range: x.precisionRange, date: summary.generated, source: SOURCE };
  }
  return rows;
}

const lines = (obj) => "{\n" + Object.entries(obj).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join("\n") + "\n}";

// The persuasion rows come from scripts/eval-persuasion.mjs and are kept as they are.
export function writeMeasured(path, summary) {
  const { families, ...rest } = summary;
  const persuasion = currentBlock(existsSync(path) ? readFileSync(path, "utf8") : "");
  const src = `// Measured accuracy per badge family, from the held-out test split in project-docs/EVALUATION.md.
// Generated by scripts/eval.mjs; do not edit. The window and the options page read MEASURED through
// families.js (measuredLine). A family with no row here shows "not measured yet".
//
// Row shape, one per family id from families.js:
//   { precision, low, high, n, split: "test", recall?, side?, date?, source? }
//   precision, low, high: 0 to 1 (low and high are the 95% interval); n: badges checked.
//   range: [lowest, highest] precision across corpora with at least 20 hits, or null.
// MEASURED_DETAIL holds every family (weak ones too), the side comparison and the SYNTHETIC
// duplicate and mismatch pilots, which are not human-labelled and get no row in MEASURED.

export const MEASURED_AT = ${JSON.stringify(summary.generated)};
${persuasion}
export const MEASURED = ${lines(tableRows(summary))};

export const MEASURED_DETAIL = {
 ${Object.entries(rest).map(([k, v]) => `${JSON.stringify(k)}: ${JSON.stringify(v)},`).join("\n ")}
 families: ${lines(families).replace(/\n/g, "\n ")},
};

export const MEASURED_DOES_NOT_PROVE = ${JSON.stringify(DOES_NOT_PROVE)};
`;
  writeFileSync(path, src.replace(/\r\n/g, "\n"));
}
