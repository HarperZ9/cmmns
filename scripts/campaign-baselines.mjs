// Engagement-shape baselines for the launch campaign lens (project-docs/CAMPAIGN-LENS.md).
//   node scripts/campaign-baselines.mjs [--data <dir>]   (default: $RADAR_DATA or ../radar-data)
// Input: <data>/pheme/prepared/pheme-shape.jsonl from scripts/eval/prep-pheme-shape.py (counts
// only: follower count, reposts and likes of each PHEME source post). Output:
// src/core/campaign-baselines-data.js and project-docs/evidence/campaign-baselines.json.
//
// PHEME is Twitter in 2014 and 2015 breaking news, so it ships only as a labelled historical
// reference. The current X strata stay empty (n = 0) until the hand-collected modern baseline
// (EVALUATION.md, launch campaigns) exists; the lens then says "insufficient baseline".
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const arg = (k, d) => { const i = process.argv.indexOf(k); return i > 0 ? process.argv[i + 1] : d; };
const DATA = arg("--data", process.env.RADAR_DATA || "../radar-data");
const FILE = join(DATA, "pheme", "prepared", "pheme-shape.jsonl");
export const MIN_INTERACTIONS = 20;
export const STRATA = [
  { label: "under 10,000 followers", min: 0, max: 1e4 },
  { label: "10,000 to 100,000 followers", min: 1e4, max: 1e5 },
  { label: "100,000 to 1 million followers", min: 1e5, max: 1e6 },
  { label: "1 million followers or more", min: 1e6, max: Infinity },
];
const PS = { q05: 0.05, q25: 0.25, q50: 0.5, q75: 0.75, q95: 0.95, q99: 0.99 };

export function quantiles(xs) {
  const s = [...xs].sort((a, b) => a - b);
  const at = (p) => s[Math.min(s.length - 1, Math.floor(p * s.length))];
  return Object.fromEntries(Object.entries(PS).map(([k, p]) => [k, Math.round(at(p) * 100) / 100]));
}

export function strataOf(rows) {
  const ok = rows.filter((r) => Number.isFinite(r.reposts) && Number.isFinite(r.likes) && Number.isFinite(r.followers) && r.reposts + r.likes >= MIN_INTERACTIONS);
  return STRATA.map((s) => {
    const xs = ok.filter((r) => r.followers >= s.min && r.followers < s.max).map((r) => r.reposts / Math.max(1, r.likes));
    return { ...s, n: xs.length, repostsPerLike: xs.length ? quantiles(xs) : null };
  });
}

function main() {
  if (!existsSync(FILE)) { console.error(`missing ${FILE}; run scripts/eval/prep-pheme-shape.py first`); process.exit(1); }
  const rows = readFileSync(FILE, "utf8").split("\n").filter(Boolean).map((l) => JSON.parse(l));
  const strata = strataOf(rows);
  const used = strata.reduce((a, s) => a + s.n, 0);
  const out = {
    x: {
      strata: STRATA.map((s) => ({ ...s, current: { n: 0, source: "hand-collected X posts, 2026 (not collected yet)" } })),
      historical: { source: `PHEME source posts, Twitter 2014 and 2015 breaking news, ${used} of ${rows.length} posts with ${MIN_INTERACTIONS} or more reposts and likes (Zubiaga et al., CC BY 4.0)`, strata },
    },
    reddit: { strata: [], historical: null },
  };
  const js = `// Generated by scripts/campaign-baselines.mjs. Do not edit. Counts and quantiles only.\nexport const CAMPAIGN_BASELINES = ${JSON.stringify(out, (k, v) => (v === Infinity ? 1e15 : v), 2)};\n`;
  writeFileSync(join(root, "src/core/campaign-baselines-data.js"), js);
  writeFileSync(join(root, "project-docs/evidence/campaign-baselines.json"), JSON.stringify({ input: "pheme-shape.jsonl", rows: rows.length, used, strata }, (k, v) => (v === Infinity ? "inf" : v), 2) + "\n");
  for (const s of strata) console.log(s.label, s.n, JSON.stringify(s.repostsPerLike));
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main();
