// Writes src/core/catalogue-data.js from catalogue/: every definition entry and the signal registry,
// so the extension can link each badge to the entries that cite it and build element tables without
// reading the repository. tests/catalogue.links.test.js fails when the file is out of date.
//   node scripts/catalogue-data.mjs          write the file
//   node scripts/catalogue-data.mjs --check  exit 1 when it differs from catalogue/
import { readFileSync, readdirSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
export const OUT = join(ROOT, "src", "core", "catalogue-data.js");

export function catalogueSource(root = ROOT) {
  const dir = join(root, "catalogue", "definitions");
  const entries = readdirSync(dir).filter((f) => f.endsWith(".json")).sort().map((f) => JSON.parse(readFileSync(join(dir, f), "utf8")));
  const registry = JSON.parse(readFileSync(join(root, "catalogue", "signals.json"), "utf8"));
  return [
    "// Generated by scripts/catalogue-data.mjs from catalogue/. Do not edit; run the script after",
    "// changing an entry. Licence: CC-BY-4.0, as the catalogue (REUSE.toml).",
    `export const SIGNAL_REGISTRY = ${JSON.stringify(registry)};`,
    "export const CATALOGUE_ENTRIES = [",
    ...entries.map((e) => `  ${JSON.stringify(e)},`),
    "];",
    "",
  ].join("\n");
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const text = catalogueSource();
  if (process.argv.includes("--check")) {
    const same = existsSync(OUT) && readFileSync(OUT, "utf8").replace(/\r\n/g, "\n") === text;
    if (!same) { console.error("src/core/catalogue-data.js is out of date: run node scripts/catalogue-data.mjs"); process.exit(1); }
    console.log("src/core/catalogue-data.js matches catalogue/");
  } else {
    writeFileSync(OUT, text);
    console.log(`src/core/catalogue-data.js: ${text.length} bytes`);
  }
}
