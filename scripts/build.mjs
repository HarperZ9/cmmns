// Bundle src/core/*.js into src/ext/core.bundle.js for the content scripts. MV3 content
// scripts cannot import ES modules, so each core file becomes a function scope that returns
// its exports, imports become reads from the modules built before it, and everything lands
// on one global, PB.
import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const ORDER = ["places.js", "similarity.js", "mismatch.js", "reddit.js", "pattern.js", "flags.js", "lexicon.js", "rhetoric.js", "report.js", "about.js", "owners.js", "xdata.js", "machine.js", "network.js", "ytdata.js", "timing.js", "langs.js", "state.js", "trail.js", "history.js"];
const ident = (f) => "M_" + f.replace(/\.js$/, "");

let body = "";
const all = [];
for (const f of ORDER) {
  let src = readFileSync(join(root, "src/core", f), "utf8");
  src = src.replace(/^import \{([^}]*)\} from "\.\/([\w-]+\.js)";$/gm, (_, names, dep) => `const {${names}} = ${ident(dep)};`);
  src = src.replace(/^import \* as (\w+) from "\.\/([\w-]+\.js)";$/gm, (_, name, dep) => `const ${name} = ${ident(dep)};`);
  const exported = [];
  src = src.replace(/^export (const|function|let|class) ([A-Za-z_$][\w$]*)/gm, (_, kind, name) => { exported.push(name); return `${kind} ${name}`; });
  body += `\n// ---- ${f}\nconst ${ident(f)} = (() => {\n${src}\nreturn { ${exported.join(", ")} };\n})();\n`;
  all.push(`...${ident(f)}`);
}
const out = `// Generated by scripts/build.mjs from src/core. Do not edit.\n(() => {\n"use strict";\n${body}\nglobalThis.PB = Object.freeze({ ${all.join(", ")} });\n})();\n`;
writeFileSync(join(root, "src/ext/core.bundle.js"), out);
console.log(`core.bundle.js: ${out.length} bytes`);
