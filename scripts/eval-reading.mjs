// Reproduces the reading-lens numbers in project-docs/READING-LENS.md from the feed-test sets.
//   node scripts/eval-reading.mjs [--data <dir>] [--split dev|heldout] [--fit] [--no-write]
// --split dev reads the dev sets (feed tests 1 to 9) only, and --fit writes src/core/reading-weights.js
// from them. --split heldout (the default) reads feed tests 10 and 11, never fits anything, and writes
// project-docs/evidence/reading-results.json and src/core/reading-measured.js. The sets hold other
// people's posts and stay on the author's machine; the results file holds counts and hashes only.

import { writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { DEV_SETS, HELDOUT_SETS, loadSet } from "./eval/reading-data.mjs";
import { readSets, score, harmRecall, trainingRows, fitLogistic } from "./eval/reading-score.mjs";
import { READING_SHIP_PRECISION, READING_SHIP_MIN_N } from "../src/core/reading.js";
import { READING_WEIGHTS } from "../src/core/reading-weights.js";
import { READING_TECHNIQUES } from "../src/core/reading-cues.js";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const arg = (name, dflt) => { const i = process.argv.indexOf(name); return i > 0 ? process.argv[i + 1] : dflt; };
const DATA = arg("--data", process.env.READING_DATA || "C:/dev/mission-control");
const SPLIT = arg("--split", "heldout");
const WRITE = !process.argv.includes("--no-write");
const pct = (r) => (r && r.n ? `${(r.value * 100).toFixed(0)}% (${r.k}/${r.n}, ${(r.ci[0] * 100).toFixed(0)} to ${(r.ci[1] * 100).toFixed(0)})` : "n/a");

function table(title, sets) {
  const withI = score(readSets(sets)), without = score(readSets(sets, { inflection: false }));
  console.log(`\n== ${title}: ${sets.reduce((a, s) => a + s.posts.length, 0)} posts`);
  for (const t of READING_TECHNIQUES) {
    const a = withI[t.id], b = without[t.id];
    if (!a.precision.n && !b.precision.n && !a.recall.n) continue;
    console.log(`  ${t.id.padEnd(20)} with: P ${pct(a.precision).padEnd(22)} R ${pct(a.recall).padEnd(22)} | without: P ${pct(b.precision).padEnd(22)} R ${pct(b.recall)}`);
  }
  const hw = harmRecall(readSets(sets)), hb = harmRecall(readSets(sets, { inflection: false }));
  console.log(`  harm-family posts with any finding: with ${pct(hw)} | without ${pct(hb)}`);
  return { with: withI, without, harm: { with: hw, without: hb } };
}

const ship = (r) => r.precision.n >= READING_SHIP_MIN_N && r.precision.value >= READING_SHIP_PRECISION;

function dev() {
  const sets = DEV_SETS.map((n) => loadSet(DATA, n));
  if (process.argv.includes("--fit")) {
    const rows = trainingRows(sets.filter((s) => s.labelled));
    const fit = fitLogistic(rows);
    console.log(`fit on ${rows.y.length} dev hits (${rows.y.filter(Boolean).length} consensus positive):`, JSON.stringify(fit));
    if (WRITE) writeFileSync(join(root, "src/core/reading-weights.js"), `// Generated by scripts/eval-reading.mjs --fit from feed tests 1 to 9 (${rows.y.length} cue hits, ${rows.y.filter(Boolean).length} consensus positive). Do not edit.\nexport const READING_WEIGHTS = ${JSON.stringify({ ...fit, threshold: 0.5 })};\n`);
    return;
  }
  table("dev, feed tests 1 to 9", sets.filter((s) => s.labelled));
}

function heldout() {
  const sets = HELDOUT_SETS.map((n) => loadSet(DATA, n));
  const unlabelled = sets.filter((s) => !s.labelled).map((s) => s.n);
  if (unlabelled.length) throw new Error(`sets without both labellers: ${unlabelled.join(", ")}`);
  const r = table("held out, feed tests 10 and 11", sets);
  const measured = Object.fromEntries(READING_TECHNIQUES.map((t) => { const x = r.with[t.id];
    return [t.id, { on: ship(x), precision: x.precision.value, k: x.precision.k, n: x.precision.n, low: x.precision.ci[0], high: x.precision.ci[1] }]; }));
  console.log(`\nships on: ${Object.entries(measured).filter(([, m]) => m.on).map(([id]) => id).join(", ") || "none"}`);
  if (!WRITE) return;
  const out = { generated: "2026-10-23", rule: { precision: READING_SHIP_PRECISION, minN: READING_SHIP_MIN_N, against: "consensus of labellers A and B, held-out feed tests 10 and 11, with inflection" },
    weights: READING_WEIGHTS, inputs: sets.flatMap((s) => s.inputs), heldout: r, measured };
  writeFileSync(join(root, "project-docs/evidence/reading-results.json"), JSON.stringify(out, null, 1) + "\n");
  writeFileSync(join(root, "src/core/reading-measured.js"), `// Generated by scripts/eval-reading.mjs from held-out feed tests 10 and 11. Do not edit.\n// on: held-out precision at least ${READING_SHIP_PRECISION * 100}% from at least ${READING_SHIP_MIN_N} hits, with inflection.\nexport const READING_MEASURED = ${JSON.stringify(measured, null, 1)};\n`);
  console.log("wrote project-docs/evidence/reading-results.json and src/core/reading-measured.js");
}

if (SPLIT === "dev") dev(); else heldout();
